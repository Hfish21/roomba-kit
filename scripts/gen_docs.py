"""Generate `docs/reference/` from the registry, profiles, error catalogue, events and CLI tree.

    uv run python scripts/gen_docs.py            # write the files
    uv run python scripts/gen_docs.py --check    # exit 1 and list stale files (CI)

Output is deterministic: sorted, no timestamps, fixed help width.
"""

import argparse
import json
import shlex
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any
from urllib.parse import urlencode

import click
from pydantic import TypeAdapter

from roomba_kit.cli.main import cli
from roomba_kit.core import registry
from roomba_kit.core.capabilities import Capability
from roomba_kit.core.contract import API_PREFIX
from roomba_kit.core.errors import CLI_EXIT, HTTP_STATUS, ErrorCode
from roomba_kit.core.events import EVENT_DATA, Event
from roomba_kit.profiles.loader import load_profiles
from roomba_kit.service.describe import describe
from roomba_kit.service.operations import load_operations

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference"
ERRORS_CONTRACT = ROOT / "docs" / "contracts" / "errors.md"
WIDTH = 88
HEADER = "<!-- Generated by scripts/gen_docs.py. Do not edit by hand. -->\n\n"
JSON_TYPES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}


def cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def type_of(schema: dict[str, Any]) -> str:
    """A short Python-ish type for a JSON schema node."""
    if ref := schema.get("$ref"):
        return str(ref).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(type_of(s) for s in schema["anyOf"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return f"list[{type_of(schema.get('items', {}))}]"
    if kind == "null":
        return "None"
    if kind == "string" and schema.get("format") in ("date-time", "date"):
        return "datetime" if schema["format"] == "date-time" else "date"
    if kind == "object" and schema.get("properties") and schema.get("title"):
        return str(schema["title"])
    if kind == "object" and isinstance(schema.get("additionalProperties"), dict):
        return f"dict[str, {type_of(schema['additionalProperties'])}]"
    return JSON_TYPES.get(str(kind), "object" if kind == "object" else "any")


def fields_table(schema: dict[str, Any], defaults: bool = False) -> list[str]:
    props = schema.get("properties", {})
    if not props:
        return ["_No fields._"]
    required = set(schema.get("required", []))
    head = "| Field | Type | Required |" + (" Default |" if defaults else "") + " Description |"
    rows = [head, "|---|---|---|" + ("---|" if defaults else "") + "---|"]
    for name, prop in props.items():
        row = f"| `{name}` | {cell(type_of(prop))} | {'yes' if name in required else 'no'} |"
        if defaults:
            row += f" {cell(json.dumps(prop['default'])) if 'default' in prop else ''} |"
        rows.append(row + f" {cell(prop.get('description', ''))} |")
    return rows


def model_doc(schema: dict[str, Any]) -> list[str]:
    """The top-level type, then the fields of it (or of its list item) when it's a model."""
    lines = [f"Type: `{type_of(schema)}`", ""]
    target = schema.get("items", schema) if schema.get("type") == "array" else schema
    if ref := target.get("$ref"):
        target = schema.get("$defs", {}).get(str(ref).rsplit("/", 1)[-1], {})
    if target.get("properties"):
        lines += fields_table(target)
    return lines


def contexts() -> dict[tuple[str, ...], click.Context]:
    """Every command in the Click tree, keyed by its path, with a context chain for help."""
    root = click.Context(
        cli,
        info_name="roomba-kit",
        terminal_width=WIDTH,
        max_content_width=WIDTH,
        help_option_names=cli.context_settings.get("help_option_names"),
    )
    found: dict[tuple[str, ...], click.Context] = {}

    def walk(ctx: click.Context, path: tuple[str, ...]) -> None:
        found[path] = ctx
        if isinstance(ctx.command, click.Group):
            for name in sorted(ctx.command.commands):
                walk(
                    click.Context(ctx.command.commands[name], info_name=name, parent=ctx),
                    (*path, name),
                )

    walk(root, ())
    return found


def usage(ctx: click.Context) -> str:
    return " ".join([ctx.command_path, *ctx.command.collect_usage_pieces(ctx)])


SERVICE_URL = "http://127.0.0.1:8765"
EXAMPLE_VALUES: dict[str, Any] = {
    "robot": "Vacuum",
    "address": "192.0.2.10",
    "rooms": ["Kitchen"],
    "room_id": "7",
    "name": "Kitchen",
    "mission_id": "MISSION_ID",
    "setting": "passes",
    "value": "two",
    "since": 42,
    "username": "you@example.com",
    "password": "YOUR_PASSWORD",
}
"""Placeholder values for required params, by name. Optional params are left out."""
EXAMPLE_OVERRIDES: dict[tuple[str, str], Any] = {
    ("token_create", "name"): "my-script",
    ("token_revoke", "name"): "my-script",
}


def example_params(op: registry.Operation) -> dict[str, Any]:
    """Placeholder values for the op's required params (a new required param must be added)."""
    params: dict[str, Any] = {}
    for name, field in op.params.model_fields.items():
        if field.is_required():
            if (op.name, name) not in EXAMPLE_OVERRIDES and name not in EXAMPLE_VALUES:
                raise KeyError(f"{op.name}: add an example value for required param {name!r}")
            params[name] = EXAMPLE_OVERRIDES.get((op.name, name), EXAMPLE_VALUES.get(name))
    return params


def cli_argv(op: registry.Operation) -> list[str]:
    """The generated command line for the example params; secrets are prompted, never args."""
    assert op.cli is not None  # noqa: S101 - callers check the surface
    params = example_params(op)
    argv = ["roomba-kit", *op.cli.group, op.cli.name]
    for name in op.cli.args:
        if name in params:
            value = params[name]
            argv += [str(v) for v in value] if isinstance(value, list) else [str(value)]
    for name, value in params.items():
        if name in op.cli.args or name in op.cli.secret:
            continue
        flag = "--" + name.replace("_", "-")
        if isinstance(value, bool):
            argv.append(flag if value else f"--no-{flag[2:]}")
        else:
            for v in value if isinstance(value, list) else [value]:
                argv += [flag, str(v)]
    return argv


def curl_line(op: registry.Operation) -> str:
    assert op.http is not None  # noqa: S101 - callers check the surface
    req = registry.http_request(op, example_params(op))
    url = SERVICE_URL + API_PREFIX + req.path
    if req.query:
        url += "?" + urlencode(req.query, doseq=True)
    parts = ["curl", "-s"]
    if req.method != "GET":
        parts += ["-X", req.method]
    if op.http.auth:
        parts += ["-H", '"Authorization: Bearer $TOKEN"']
    if req.body is not None:
        parts += ["-H", '"Content-Type: application/json"', "-d", shlex.quote(json.dumps(req.body))]
    return " ".join([*parts, shlex.quote(url)])


def mcp_call(op: registry.Operation) -> str:
    """A JSON-RPC `tools/call` request for the example params."""
    call = {
        "jsonrpc": "2.0",
        "id": 1,
        "method": "tools/call",
        "params": {"name": op.name, "arguments": example_params(op)},
    }
    return json.dumps(call)


def examples(op: registry.Operation) -> list[str]:
    out = ["**Examples**", ""]
    if "cli" in op.surfaces and op.cli:
        line = shlex.join(cli_argv(op))
        prompted = ", ".join(op.cli.secret)
        out += ["```bash", line + (f"  # prompts for {prompted}" if prompted else ""), "```", ""]
    if "http" in op.surfaces and op.http:
        out += ["```bash", curl_line(op), "```", ""]
    if "mcp" in op.surfaces:
        out += ["```json", mcp_call(op), "```", ""]
    return out


def operations_md() -> str:
    tree = contexts()
    out = [
        "# Operations",
        "",
        "Every capability, as it appears on HTTP, MCP and the CLI.",
        "",
        "Examples use placeholder values for the required parameters (the robot `Vacuum`, the",
        "room `Kitchen`, `MISSION_ID` from `missions list`): replace them with yours. `$TOKEN` is",
        "an API token (`roomba-kit token create NAME`); the MCP example is the JSON-RPC request an",
        "MCP client sends to `/mcp` or `roomba-kit mcp`.",
        "",
    ]
    for op in registry.all():
        out += [f"## `{op.name}`", ""]
        out += [p for p in describe(op).split("\n\n") if not p.startswith("Parameters:")]
        out += ["", "| Surface | Usage |", "|---|---|"]
        http = op.http
        if "http" in op.surfaces and http:
            note = "" if http.auth else " (no auth)"
            out.append(f"| HTTP | `{http.method} {API_PREFIX}{http.path}`{note} |")
        else:
            out.append("| HTTP | not on HTTP |")
        out.append(
            f"| MCP | tool `{op.name}` |" if "mcp" in op.surfaces else "| MCP | not on MCP |"
        )
        cli_ctx = tree.get((*op.cli.group, op.cli.name)) if op.cli else None
        if "cli" in op.surfaces and cli_ctx:
            only = " (CLI only)" if op.surfaces == {"cli"} else ""
            out.append(f"| CLI | `{cell(usage(cli_ctx))}`{only} |")
        else:
            out.append("| CLI | not on the CLI |")
        out += ["", *examples(op)]
        out += [
            "**Parameters**",
            "",
            *fields_table(op.params.model_json_schema(), defaults=True),
        ]
        schema = TypeAdapter(op.result).json_schema(mode="serialization", by_alias=True)
        out += ["", "**Result**", "", *model_doc(schema), ""]
    return "\n".join(out)


def error_meanings() -> dict[str, str]:
    meanings = {}
    for line in ERRORS_CONTRACT.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split(" | ")]
        if len(cells) == 4 and cells[0].startswith("`"):
            meanings[cells[0].strip("`")] = cells[1]
    return meanings


def errors_md() -> str:
    meanings = error_meanings()
    out = [
        "# Errors",
        "",
        'Every surface returns these codes. HTTP bodies are `{"error": {"code", "message", '
        '"robot_id"?, "details"?}}`. The CLI exits 0 on success.',
        "",
        "| Code | Meaning | HTTP | CLI exit |",
        "|---|---|---|---|",
    ]
    for code in ErrorCode:
        http = HTTP_STATUS.get(code, "—")
        out.append(f"| `{code.value}` | {meanings[code.value]} | {http} | {CLI_EXIT[code]} |")
    out += [
        "",
        "`unconfirmed` is an outcome, not a failure: HTTP returns 202 with a CommandResult, MCP "
        'returns a normal result with `outcome: "unconfirmed"`, and the CLI exits 3.',
        "",
    ]
    return "\n".join(out)


def events_md() -> str:
    out = ["# Events", "", "## Envelope", "", *fields_table(Event.model_json_schema(by_alias=True))]
    for kind in sorted(EVENT_DATA, key=lambda k: k.value):
        model = EVENT_DATA[kind]
        out += ["", f"## `{kind.value}`", "", f"`data`: `{model.__name__}`", ""]
        out += fields_table(model.model_json_schema(by_alias=True))
    return "\n".join([*out, ""])


def support_matrix_md() -> str:
    profiles = sorted(load_profiles().values(), key=lambda p: p.id)
    out = [
        "# Support matrix",
        "",
        "✅ verified on hardware · ⚪ declared, unverified · — not supported",
        "",
        "| Capability | " + " | ".join(f"`{p.id}`" for p in profiles) + " |",
        "|---|" + "---|" * len(profiles),
    ]
    runs = []
    for cap in Capability:
        marks = []
        for p in profiles:
            v = p.capabilities.get(cap)
            marks.append("—" if v is None else "✅" if v.is_verified else "⚪")
            if v is not None and v.is_verified:
                runs.append(f"- `{p.id}` `{cap.value}`: {v.run}")
        out.append(f"| `{cap.value}` | " + " | ".join(marks) + " |")
    out += ["", "## Profiles", ""]
    out += [f"- `{p.id}`: {p.display_name}" for p in profiles]
    if runs:
        out += ["", "## Verification runs", "", *runs]
    return "\n".join([*out, ""])


def cli_md() -> str:
    out = ["# CLI", ""]
    for path, ctx in sorted(contexts().items()):
        title = " ".join(("roomba-kit", *path))
        out += [f"## `{title}`", "", "```text", ctx.command.get_help(ctx).rstrip(), "```", ""]
    return "\n".join(out)


PAGES: dict[str, Callable[[], str]] = {
    "operations.md": operations_md,
    "errors.md": errors_md,
    "events.md": events_md,
    "support-matrix.md": support_matrix_md,
    "cli.md": cli_md,
}


def render() -> dict[str, str]:
    load_operations()
    return {name: HEADER + build() for name, build in PAGES.items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any file is stale")
    parser.add_argument("--out", type=Path, default=OUT, help="output directory")
    args = parser.parse_args(argv)
    pages = render()
    if args.check:
        stale = [
            name
            for name, text in pages.items()
            if not (args.out / name).exists() or (args.out / name).read_text("utf-8") != text
        ]
        for name in stale:
            print(f"stale: {args.out / name}", file=sys.stderr)
        if stale:
            print("Run: uv run python scripts/gen_docs.py", file=sys.stderr)
        return 1 if stale else 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (args.out / name).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
